/**
 * Figma -> code for design tokens. Reads the W3C DTCG JSON exported from Figma Variables
 * (src/theme/design-tokens.json) and writes src/theme/tokens.css:
 *   primitive.<path>  -> :root { --<path> }            raw values, no utilities
 *   semantic.<ns>.<n> -> @theme { --<ns>-<n> }          Tailwind utilities (bg-primary, rounded-card)
 *   typography        -> --text-<n> + --line-height / --font-weight sub-tokens (text-title)
 *   shadow            -> --shadow-<n> as a CSS box-shadow (shadow-overlay)
 *   "{primitive.a.b}" -> var(--a-b)                     aliases stay aliases
 * Run: pnpm tokens
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

type Node = { [key: string]: unknown; $type?: string; $value?: unknown; $description?: string };
export type Tokens = { primitive: Node; semantic: Node };

const cssName = (path: string[]) => `--${path.join('-')}`;

const alias = (raw: string) => {
  const match = /^\{(?:primitive\.)?(.+)\}$/.exec(raw);
  return match?.[1] ? `var(${cssName(match[1].split('.'))})` : raw;
};

/** DTCG 2025 object values: colors carry `hex`, dimensions carry `value` + `unit`. */
const objectValue = (raw: { hex?: string; value?: number; unit?: string }) => {
  if (raw.hex) return raw.hex;
  if (raw.value !== undefined) return `${raw.value}${raw.unit ?? ''}`;
  throw new Error(`Unsupported token value: ${JSON.stringify(raw)}`);
};

const value = (raw: unknown): string => {
  if (typeof raw === 'string') return alias(raw);
  if (typeof raw === 'number') return String(raw);
  if (Array.isArray(raw)) return raw.join(', ');
  if (raw && typeof raw === 'object') return objectValue(raw);
  throw new Error(`Unsupported token value: ${JSON.stringify(raw)}`);
};

/** DTCG shadow: one object or a list of them -> CSS box-shadow. */
const shadow = (raw: unknown) =>
  (Array.isArray(raw) ? raw : [raw])
    .map((layer) => {
      const { blur, color, offsetX, offsetY, spread = 0 } = layer as Record<string, unknown>;
      return [offsetX, offsetY, blur, spread, color].map(value).join(' ');
    })
    .join(', ');

/** DTCG typography -> Tailwind font-size token plus its line-height / font-weight sub-tokens. */
const typography = (name: string, raw: unknown, comment: string) => {
  const { fontSize, fontWeight, lineHeight } = raw as Record<string, unknown>;
  return [
    `  ${name}: ${value(fontSize)};${comment}`,
    ...(lineHeight === undefined ? [] : [`  ${name}--line-height: ${value(lineHeight)};`]),
    ...(fontWeight === undefined ? [] : [`  ${name}--font-weight: ${value(fontWeight)};`]),
  ];
};

const leaf = (node: Node, path: string[], type: string | undefined) => {
  const comment = node.$description ? ` /* ${node.$description} */` : '';
  if (type === 'typography') return typography(cssName(path), node.$value, comment);
  const css = type === 'shadow' ? shadow(node.$value) : value(node.$value);
  return [`  ${cssName(path)}: ${css};${comment}`];
};

/** Walks a DTCG group and returns CSS declarations; `$type` is inherited from parent groups. */
const declarations = (node: Node, path: string[], type?: string): string[] => {
  const ownType = node.$type ?? type;
  if ('$value' in node) return leaf(node, path, ownType);
  return Object.entries(node)
    .filter(([key]) => !key.startsWith('$'))
    .flatMap(([key, child]) => declarations(child as Node, [...path, key], ownType));
};

export const buildTokensCss = (tokens: Tokens) => {
  const namespaces = Object.keys(tokens.semantic).filter(
    (key) => !key.startsWith('$') && !('$value' in (tokens.semantic[key] as Node)),
  );

  return `/* GENERATED by scripts/build-tokens.ts from design-tokens.json. Do not edit: run \`pnpm tokens\`. */

/* Primitives: raw Figma values. Not exposed as utilities. */
:root {
${declarations(tokens.primitive, []).join('\n')}
}

/* Semantic tokens: the only values components may use. */
@theme {
  /* Tailwind defaults removed: only the tokens below exist (bg-blue-500 renders nothing). */
${namespaces.map((ns) => `  --${ns}-*: initial;`).join('\n')}

${declarations(tokens.semantic, []).join('\n')}
}
`;
};

// Run only when executed (`pnpm tokens`), not when imported by the test.
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const source = new URL('../src/theme/design-tokens.json', import.meta.url);
  const target = new URL('../src/theme/tokens.css', import.meta.url);
  writeFileSync(target, buildTokensCss(JSON.parse(readFileSync(source, 'utf8')) as Tokens));
  console.log('tokens.css written.');
}
